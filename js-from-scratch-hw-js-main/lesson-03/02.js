// Разработайте функцию isEven, которая определяет, чётное ли число.
// Функция должна возвращать true, если число чётное, и false — в противном случае
function isEven(a) {
    if (a % 2 === 0) {
        isEven = true;
        console.log("Число четное")
    } else {
        isEven = false;
        console.log("Число нечетное")

    }
return isEven;
}
